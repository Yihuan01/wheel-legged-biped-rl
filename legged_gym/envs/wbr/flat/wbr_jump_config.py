#   P8J3c  行进回合浅蹲，起点 1c@4950                     ✅ dip 0.70→0.78（交付候选 5300）
#   P8J3d  浅蹲＋轮速跟随回归，起点 3c@5300              ＝dip +1pp 持平、事件末 1.20
#   P8J3f  跟随增益×2，起点 3d@5650                      ❌ 回退线触发（站跳 0.15 -6.3mm）
#   P8J4a  行进回合前跳 tilt 9°，起点 3d@5650            ＝dx/net 持平，tilt 回退
#   P8J4b  反刹车单边项，起点 3d@5650                     ❌ 回退线触发（站跳/dip/net 恶化）
