from legged_gym.envs.wbr.flat.wbr_flat_config import WBRFlatCfg, WBRFlatCfgPPO


class WBRJumpCfg(WBRFlatCfg):
    """P8J3d 交付态（P8J5 三轮新族全部回退后复位）：浅蹲 dose-1＋轮速跟随 boost1.0。
    交付 releases/P8J3d_wheelfollow_lite@5650；P8J5 结论见 releases/P8J5_attempt/。

    【要攻的难题】P6 五次尝试从未做成「真跳高随指令单调」，b 轮 4775 是 61.7/96.3/100.4
    —— 0.10 与 0.15 只差 4.1 mm（判据要 ≥8 mm）。

    【为什么分化难】R81 与 b 轮的读数都显示**两端同时塌向中间**：
      · 低档（目标 70 mm）实测 84.3~61.7 mm ⇒ **超额交付**（策略本来就蹬得比要求狠）；
      · 高档（目标 130 mm）实测 100.1 mm ⇒ **物理封顶**（两轮腿长+行程的上限就在 100~106）。
    两端一挤，三档自然挤在一起。抬高方向已三次证否（R61/R72b 扩量程全塌、R77b 动作好但稳定性退）。
    ⇒ **分化只能靠"压低低档"**：让低指令真的只用小力气跳。

    【三个锚点怎么动】都是 `(h_lo, h_hi, v_lo, v_hi)` 线性插值，改低端锚点会连带下压中档：
      · `top_height_goal_by_h` 0.070 → **0.045**（轮底目标直降 25 mm；高档 0.130→0.135）
      · `burst_L_by_h`        0.29  → **0.275**（爆发目标腿长更短 ⇒ 蹬地行程更短 ⇒ 冲量更小）
      · `crouch_abs_by_h`     0.22  → **0.235**（低档预蹲更浅 ⇒ 可用的伸展行程更少）
    高档锚点反向微调（0.130→0.135、0.38→0.385、0.19→0.188），让高档继续贴物理上限。

    【附带保留 b 轮的全部能力】前进中起跳的三道门、体高带、观测噪声一律不动——
    c 轮只动高度分化这三个锚点，不引入第二个变量方向。
    """

    class commands(WBRFlatCfg.commands):
        # ---- 跳跃回合 / 指令（= b 轮，不动）----
        jump_command_probability = 1.0
        jump_stand_ratio = 0.5           # 一半行走回合，保住"边走边跳"样本

        # ---- 三道门（= b 轮，不动）----
        jump_vx_gate = 0.6               # 指令侧速度门
        jump_yaw_gate = 0.10             # 暂不放宽：先只开直行中起跳
        jump_roll_gate = 0.10

        # ---- 体高指令带（= b 轮，不动）----
        jump_cmd_h_min = 0.24
        jump_cmd_h_max = 0.32
        jump_stand_height = [0.28, 0.30]

        class ranges(WBRFlatCfg.commands.ranges):
            lin_vel_x = [-0.6, 0.6]
            # ⚠ 体高观测按本量程归一化（wbr_flat.py: h_half = max((hi-lo)/2, 1e-6)）
            #   ⇒ 零宽量程会把观测炸到 1e4 量级（a 轮预飞踩过，见 11-02 日志）
            base_height = [0.24, 0.30]
            ang_vel_yaw = [-0.8, 0.8]

    class rewards(WBRFlatCfg.rewards):
        # hinge 带宽回 R81 值（源码现值是 W3 行走线调参产物）
        velocity_tracking_error_limit = 1.1
        height_tracking_error_limit = 0.20

        # 【P8J4b 已回退】wheel_no_brake=-3.0 撤下：实测 net_dx −112/−13 vs 基线 −61/+11、
        #   dip 恶化 8~10pp、滑移升、站跳 h0.10 −6.1mm 触发回退线 ⇒ 反刹车惩罚让策略
        #   整体变差，坐实「预蹲/蹬地段轮子刹车是功能性行为（策略用它管理后仰甩尾）」。
        #   至此轮子问题三种机制全部实测关闭（奖多转 3a/3b、轻奖 3d/3f、罚刹车 4b），
        #   3d 的 wheel-follow boost=1.0 即最优剂量。代码 _reward_wheel_no_brake 留档。

        class jump(WBRFlatCfg.rewards.jump):
            # ---- 前进中起跳：实测侧站定门关闭（= b 轮）----
            # `cmd_settle_gate=True` 时要求实测水平速度 ≤0.10 连续 30 拍才发跳指令
            # ⇒ 结构上禁止前进中起跳。这是三道门里最容易漏的一道。
            cmd_settle_gate = False

            # ================= 【行进回合跟随（2a→3d 演化，现态＝P8J3d）】=================
            # 历史：2a 全程放开蹬地段 vx 跟随 ⇒ 站跳 −4~6.6 mm 回退；2b 择相门极性写反
            #   （is_jump_round=站立回合）＝行进 no-op，P8J3a 起极性改正（~is_jump_round）。
            #   mask 一律不覆写（父类 [2,3,4]），开关在奖励函数里按回合择相。
            # 3a/3b 轮速跟随两连负（烧胎：轮快转、机体 dip 反而更深、事件末恶化）⇒ 曾封存；
            # 3c 行进回合浅蹲正结果（dip_frac 0.70→0.78，机制＝后仰甩尾被定量证实）。
            # 【P8J3d→3f 现态】作者指令（11-02 [19:2x]）：预蹲/蹬地段继续转轮子。
            #   3d（回归，无增益）＝dip +1pp 持平、烧胎未复现、事件末 h0.15 升到 1.20
            #   ⇒ 浅蹲基面上轮速跟随无害但弱梯度推不动行为；3f 试过增益 ×2＝dip 恶化
            #   6pp/2pp＋站跳 0.15 档 -6.3mm 回退线触发（releases/P8J3f_boost2x/ 留档）
            #   ⇒ 剂量结论：轮速跟随「开而不增」是可用上限，工作区回退到 3d 交付态（boost 1.0）。
            # 蹬地段 base-vx 跟随（vx_follow_in_jump_round）：极性修复后对行进回合生效，保留。
            vx_follow_in_jump_round = True
            wheel_follow_in_jump_round = True
            wheel_follow_phases = (1, 2)
            wheel_follow_boost = 1.0
            # ==================================================================

            # ================= 【P8J3c 保留：行进回合浅蹲（模板侧）】=================
            # Step0 归因（eval_runs/2026-11-02_P8J3保速基线/attr_tsv.py）：蹲段机体减速主体
            #   ＝模板后仰 ~20° 的运动学甩尾（锚点曲线只解释 1%），蹲越深甩越多；v27 附记
            #   「蹲深不兑换高度」。行进回合（|cmd_vx|>moving_crouch_vx_gate）蹲浅一档：
            #   h0.15 0.188→0.213（−25 mm 深度）、h0.10 插值 −12.5 mm、低档不动。
            #   站立回合（未过门）逐字 1c 行为。3c 实测 dip_frac h0.15 0.70→0.78。
            # 【P8J4d 已回退 → 3d 交付态】更浅 dose-2（0.225）实测：net_dx −51/−17 vs 基线
            #   −61/+11（噪声带内）、dx_air 持平略降、dip 持平（dose-1 的 +8pp 未延续＝饱和）；
            #   站跳副产物 +3.7/+6.2/+6.8（0.15 档 99.0mm）但主判据不动 ⇒ 回退 3d 交付态（0.213）。
            crouch_abs_by_h_moving = (0.05, 0.15, 0.235, 0.213)
            moving_crouch_vx_gate = 0.3
            # ==================================================================

            # ================= 【P8J4c 已回退：更快预蹲 ramp_end 0.42】=================
            # 4c 实测（双 seed 中位）：net_dx −78/−16 vs 基线 −61/+11（无改善）、dip 恶化
            # 5~7pp、g1=1.00（伺服跟上了但没兑换成净前进）⇒ 键撤下（代码路径保留）。
            # ==================================================================

            # ================= 【P8J5b 已回退：空中收腿放松 0.215】=================
            # 5b 实测（双 seed 中位）：dx_air 74/93 vs 基线 73/99（持平）、net 无改善、
            #   dip 恶化 7~8pp（>3pp 线）⇒ 回退（键撤下，代码路径保留）。
            #   15mm 放松没减到「空中刹车」反而扰动蹲-蹬动力学；该机理的可用剂量可能
            #   远小于 15mm 或需要与别的轮次耦合，本轮不再追。
            # ==================================================================

            # ================= 【P8J5c 已回退：预蹲少等 hold 0.05】=================
            # 5c 实测（双 seed 中位）：net_dx −94/−25.5 vs 基线 −61/+11（明确恶化）、
            #   dip 恶化 12~13pp、g1=1.00 ⇒ 回退（键撤下，代码路径保留）。
            #   hold 0.10s 实际是推蹬前的稳定预备，砍掉后推蹬质量全面下降——「纯等待」
            #   的假设被否证。至此 P8J5 三新族（前跳定价/空中收腿放松/预蹲少等）全部回退。
            # ==================================================================

            # ================= 【P8J4a 已回退：行进回合前跳 tilt 9°】=================
            # 4a 实测（双 seed）：dx_air_int 71/97 vs 基线 73/99（持平）、net_dx −70/−3 vs
            # −61/+11（噪声带内略差）、dip h0.15 −3~4pp、蹲末俯仰 −4°（如设计）但未兑换成
            # 前向距离 ⇒ 键撤下（代码路径保留，anchor_tilt_deg_moving=None 即旧行为）。
            # 勘误留档见 releases/P8J4a_*（若立包）与预注册计划 §3。
            # ==================================================================

            # ================= 【c 轮：高度分化三锚点（保留）】=================
            # 低端下压（分化来源），高端继续贴物理上限。中档被线性插值连带下压：
            #   0.05→v_lo，0.10→(v_lo+v_hi)/2，0.15→v_hi
            top_height_goal_by_h = (0.05, 0.15, 0.045, 0.135)
            #   原 (0.05, 0.15, 0.070, 0.130) ⇒ 中档目标 100 mm → 90 mm
            burst_L_by_h = (0.05, 0.15, 0.275, 0.385)
            #   原 (0.05, 0.15, 0.29, 0.38)  ⇒ 中档目标腿长 0.335 → 0.330
            crouch_abs_by_h = (0.05, 0.15, 0.235, 0.188)
            #   原 (0.05, 0.15, 0.22, 0.19)  ⇒ 中档预蹲 0.205 → 0.2115（更浅=行程更少）
            # ==================================================================

    class noise(WBRFlatCfg.noise):
        """噪声/随机化逐步放开（用户 2026-11-02 定）：
        a 全关 → **b/c 观测噪声开** → 后续轮物理侧 DR → 更晚传感器侧 DR。"""
        add_noise = True
        noise_level = 1.0

    class domain_rand(WBRFlatCfg.domain_rand):
        """DR 仍全关（本轮不加第二维度）。惰性键不改写，理由见 11-02 日志：
        总闸关 ⇒ 代码不读；判定式 hi>lo 恒假 ⇒ 直接跳过；R81 前不存在的键全退化。
        `terrain.curriculum` 源码 True 但 `_parse_cfg` 对 plane 强制置 False。"""
        pass


class WBRJumpCfgPPO(WBRFlatCfgPPO):
    class algorithm(WBRFlatCfgPPO.algorithm):
        # 热启动护栏：3e-4 → 1e-4（W 线四连败的处置结论）
        learning_rate = 1.0e-4

    class runner(WBRFlatCfgPPO.runner):
        experiment_name = "wbr_jump"
        run_name = "P8J3d"
        max_iterations = 350
        save_interval = 25
