#   P8J5a  一次性前跳奖 300，起点 3d@5650                 ❌ 站跳 h0.10 −5.7mm 回退线（双seed确认）
#   P8J5b  空中收腿放松 0.215，起点 3d@5650               ❌ dip 恶化 7~8pp 回退
#   P8J5c  预蹲少等 hold 0.05，起点 3d@5650               ❌ net/dip 明确恶化，回退
